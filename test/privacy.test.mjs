import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createApp } from '../server.mjs';

test('Pair membership, private wallets, amounts and idempotency through HTTP', async () => {
  const server = createApp();
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const base = `http://127.0.0.1:${server.address().port}/api/`;
  async function request(path, body, token) {
    const response = await fetch(base + path, { method: body ? 'POST' : 'GET', headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${token || ''}` }, body: body ? JSON.stringify(body) : undefined });
    return { status: response.status, ...await response.json() };
  }
  try {
    const a = await request('register', { name: 'Аня', login: 'anna', password: 'test-password-1' });
    const b = await request('register', { name: 'Борис', login: 'boris', password: 'test-password-2' });
    const c = await request('register', { name: 'Третий', login: 'third', password: 'test-password-3' });
    assert.equal(a.status, 200);
    assert.equal((await request('login', { login: 'anna', password: 'wrong-password' })).status, 401);
    const invite = await request('invite', {}, a.token);
    assert.equal((await request('join', { code: invite.code }, b.token)).status, 200);
    assert.equal((await request('join', { code: invite.code }, c.token)).status, 400);
    assert.equal((await request('invite', {}, a.token)).status, 409);
    const goal = {id:'saving',title:'Отпуск',wallet:'personal',target:100000,deadline:null};
    assert.equal((await request('goal',goal,a.token)).status,200);
    assert.equal((await request('goal',{...goal,id:'trip',wallet:'shared',deadline:'2027-01-10'},a.token)).status,200);
    assert.equal((await request('goal',{...goal,id:'bad',deadline:'2027-02-30'},a.token)).status,400);
    const deposit = {goal:'trip',id:'transfer',amount:20000};
    assert.equal((await request('deposit',deposit,b.token)).status,200);
    assert.equal((await request('deposit',deposit,b.token)).status,200);
    assert.equal((await request('deposit',{...deposit,goal:'saving'},b.token)).status,404);
    const goals = (await request('state',undefined,b.token)).goals;
    assert.equal(goals.length,1);
    assert.equal(goals[0].saved,20000);
    assert.deepEqual((await request('state',undefined,c.token)).goals,[]);
    const entry = { wallet: 'shared', kind: 'income', amount: 4000000, category: 'Зарплата', date: '2026-11-04', note: '', requestId: 'shared-income' };
    assert.equal((await request('entries', entry, a.token)).status, 200);
    assert.equal((await request('entries', entry, a.token)).status, 200);
    await request('entries', { ...entry, wallet: 'personal', amount: 1500000, requestId: 'private-income' }, a.token);
    await request('entries', { ...entry, wallet: 'personal', kind: 'expense', amount: 12345, category: 'Секрет', requestId: 'private-expense' }, a.token);
    await request('entries', { ...entry, wallet: 'personal', amount: 9876, requestId: 'b-income' }, b.token);
    const aState = await request('state', undefined, a.token);
    const bState = await request('state', undefined, b.token);
    assert.equal(aState.entries.length, 3);
    assert.equal(bState.entries.length, 2);
    assert.equal(bState.entries.some(item => item.category === 'Секрет'), false);
    assert.equal(JSON.stringify(bState).includes('1500000'), false);
    assert.equal(aState.entries.some(item => item.amount === 9876), false);
    const personal = aState.entries.find(item => item.category === 'Секрет');
    const edit = {...entry, id:personal.id, kind:'expense', wallet:'personal', category:'Здоровье', amount:321};
    assert.equal((await request('edit-entry', edit, b.token)).status, 404);
    assert.equal((await request('delete-entry', {id:personal.id}, b.token)).status, 404);
    assert.equal((await request('edit-entry', edit, a.token)).status, 200);
    const rename = {wallet:'personal',kind:'expense',name:'Здоровье',replacement:'Аптека'};
    assert.equal((await request('category', rename, a.token)).status, 200);
    const renamed = await request('state', undefined, a.token);
    assert.equal(renamed.entries.find(row => row.id === personal.id).category,'Аптека');
    assert.equal(JSON.stringify(await request('state', undefined, b.token)).includes('Аптека'),false);
    assert.equal((await request('category', {...rename,name:'Аптека',replacement:null}, a.token)).status,200);
    const moved = (await request('state', undefined, a.token)).entries.find(row => row.id === personal.id);
    assert.equal(moved.category,'Без категории');
    assert.equal(moved.amount,321);
    const items = [{name:'Чай',price:321}];
    assert.equal((await request('edit-entry',{...edit,category:'Без категории',items},a.token)).status,200);
    assert.deepEqual((await request('state',undefined,a.token)).entries.find(e=>e.id===personal.id).items,items);
    assert.equal(JSON.stringify(await request('state',undefined,b.token)).includes('Чай'),false);
    assert.equal((await request('edit-entry', {...edit,category:'Без категории',amount:0}, a.token)).status,200);
    assert.equal((await request('state', undefined, a.token)).entries.find(row => row.id === personal.id).amount,0);
    const category = {wallet:'personal',kind:'expense',name:'Кот'};
    assert.equal((await request('add-category',category,a.token)).status,200);
    assert.equal((await request('state',undefined,a.token)).categories.some(row => row.name === 'Кот'),true);
    assert.equal((await request('state',undefined,b.token)).categories.some(row => row.name === 'Кот'),false);
    assert.equal((await request('delete-entry', {id:personal.id}, a.token)).status,200);
    assert.equal((await request('state', undefined, c.token)).entries.length, 0);
    assert.equal((await request('entries', { ...entry, amount: 0, requestId: 'bad-amount' }, a.token)).status, 400);
    assert.equal((await request('entries', { ...entry, date: '2026-02-30', requestId: 'bad-date' }, a.token)).status, 400);
    assert.equal((await request('entries', entry, c.token)).status, 400);
    assert.equal((await request('state')).status, 401);
    await request('logout', {}, a.token);
    assert.equal((await request('state', undefined, a.token)).status, 401);
  } finally { await new Promise(resolve => server.close(resolve)); }
});
